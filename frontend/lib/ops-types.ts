// Shapes of the operations API (fraudlens/api/routes/operations.py). Money is integer paise.
export const CHANNELS = ["upi", "net_banking", "card", "atm"] as const;
export type Channel = (typeof CHANNELS)[number];
export type Transaction = {
  txn_id: string;
  account_id: string;
  channel: Channel;
  amount_minor: number;
  timestamp: string;
  instrument_id: string | null;
  beneficiary_id: string | null;
  merchant_id: string;
  device_id: string;
  ip_address: string;
  location: string;
  new_device: boolean;
  new_beneficiary: boolean;
  failed_auth_attempts: number;
  score: number;
  payment_status: string;
  bank_reason: string | null;
  case_id: string | null;
};
export type BankAction = {
  action_id: string;
  case_id: string;
  operation: "restrict" | "release" | "lien" | "lien_release" | "close";
  amount_minor?: number;
  target_type: "account" | "card";
  target_id: string;
  status: "pending" | "confirmed" | "failed" | "superseded";
  attempts: number;
  bank_reference: string | null;
  last_error: string | null;
  created_at: string;
  updated_at: string;
};
export type AuditEvent = {
  id: number;
  event_type: string;
  case_id: string | null;
  txn_id: string | null;
  actor: string;
  message: string;
  occurred_at: string;
  metadata: Record<string, unknown>;
};
export type Case = {
  case_id: string;
  txn_id: string;
  account_id: string;
  channel: Channel;
  amount_minor: number;
  score: number;
  severity: string;
  status: string;
  verdict: string;
  version: number;
  created_at: string;
  updated_at: string;
  assigned_to: string | null;
  assignee?: string | null;
  assigned_at?: string | null;
  pending_approval?: PendingApproval | null;
  handled_by?: string[];
  priority?: number;
  priority_reason?: string;
  case_type?: "detector" | "complaint";
  complaint?: {
    complaint_id: string;
    source: "1930_helpline" | "ncrp_portal" | "branch";
    victim_account_id: string;
    reported_txn_id: string;
    reported_at: string;
  };
  trace?: TraceHop[];
  traced_total_minor?: number;
  held_total_minor?: number;
  funds_moved_total_minor?: number;
  default_target_account_id?: string | null;
  brief?: Brief;
  notes: string;
  signals: { name: string; score: number; reasons: string[] }[];
  reasons: string[];
  related_transactions: Transaction[];
  related_accounts: string[];
  actions: BankAction[];
  timeline: AuditEvent[];
};
export type Counts = {
  transactions: number;
  pending_payments: number;
  posted: number;
  declined: number;
  cases: number;
  pending_review: number;
  investigating: number;
  escalated: number;
  resolved: number;
  confirmed_fraud: number;
  false_positives: number;
  restricted_accounts: number;
  restricted_cards: number;
  pending_actions: number;
  failed_actions: number;
};
export type Snapshot = {
  cursor: number;
  as_of: string;
  simulation: true;
  counts: Counts;
  channels: {
    channel: Channel;
    transactions: number;
    cases: number;
    pending_review: number;
    confirmed_fraud: number;
    resolved: number;
    declined: number;
  }[];
  transactions: Transaction[];
  cases: Case[];
  actions: BankAction[];
  events: AuditEvent[];
  bank: {
    connected: boolean;
    mode: string;
    accounts: {
      account_id: string;
      balance_minor: number;
      available_minor: number;
      status: "active" | "frozen" | "closed";
      liens: { lien_id: string; case_id: string; amount_minor: number }[];
      restricted: boolean;
      active_restrictions: number;
    }[];
    last_error: string | null;
  };
  team?: TeamMember[];
  approvals?: (PendingApproval & { case_id: string })[];
  agent?: AgentState;
  simulation_state: { running: boolean; interval_seconds: number };
  detection: { version: string; coverage: Record<string, unknown>[] };
};
export type Decision = "investigate" | "escalate" | "confirm_fraud" | "false_positive";
export type Role = "l1_analyst" | "l2_analyst" | "supervisor";
export type CaseAction =
  Decision | "restrict" | "place_lien" | "release_lien" | "close_account" | "file_ncrp_report";
export type ApprovalAction = Exclude<CaseAction, "investigate" | "escalate" | "place_lien">;
export type PendingApproval = {
  approval_id: string;
  action: ApprovalAction;
  requested_by: string;
  required_role: Role;
  notes: string;
  requested_at: string;
  target_account_id?: string | null;
};
export type TraceHop = {
  hop: number;
  account_id: string;
  inbound_txn_ids: string[];
  traced_minor: number;
  available_minor: number;
  lien_minor: number;
  moved_minor?: number;
  lien_status?: string;
  outcome: "held" | "partially_recovered" | "funds_moved" | "account_closed" | "pending" | "released";
};
export type Brief = {
  typology: string;
  summary: string;
  evidence: string[];
  recommended_action: CaseAction;
  target_account_id: string | null;
  amount_minor: number | null;
  required_role: Role;
  required_role_label: string;
  confidence: "low" | "medium" | "high";
  next_steps: string[];
  ncrp_narrative: string;
  generated_by: "template" | "llm";
};
export type TeamMember = {
  username: string;
  display_name: string;
  role: Role;
  role_label: string;
  online: boolean;
  last_seen: string | null;
  current_case_id: string | null;
  open_assigned: number;
  resolved_today: number;
};
export type AgentState = {
  auto_assign: boolean;
  briefs_drafted: number;
  liens_placed: number;
  cases_auto_assigned: number;
  cases_triaged: number;
};
export type Guidance = {
  references: {
    id: string;
    title: string;
    source_url: string;
    source_date: string;
    applicability: string;
    control: string;
    status: string;
    test_evidence: string[];
  }[];
  requirements?: {
    issuer: string;
    source: string;
    url: string | null;
    date: string;
    status: string;
    what_it_requires: string;
    how_fraudlens_models_it: string;
    not_covered: string;
  }[];
  disclaimer: string;
};
